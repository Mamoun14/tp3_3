public class Adresse {
    private int numero;
    private String rue;
    private String codepostal;
    private String ville;

    public Adresse(int numero, String rue, String codepostal, String ville){
        this.ville = ville;
        this.rue = rue;
        this.numero = numero;
        this.codepostal = codepostal;
    }



}
